#include "ft_list.h"
#include <stdlib.h>

t_list	*ft_create_elem(void *data)
{
	t_list	*elem;

	elem = malloc(sizeof(t_list));
	if (!elem)
		return (NULL);
	elem->data = data;
	elem->next = NULL;
	return (elem);
}

#include <stdio.h>
int	main(void)
{
	t_list	*elem;

	elem = ft_create_elem("coucou");
	printf("%s\n", elem->data);
	return (0);
}
